export function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]
}

export function randomInt(min: number, max: number): number {
  return Math.floor(Math.random() * (max - min + 1)) + min
}

export function randomNorwegianPhone(): string {
  const prefixes = ['90', '91', '92', '93', '94', '95', '96', '97', '98', '99']
  const prefix = pickRandom(prefixes)
  const rest = String(randomInt(100000, 999999))
  return `+47${prefix}${rest}`
}

export function randomOrgNumber(): string {
  return String(randomInt(800000000, 999999999))
}

export function randomEmail(forename: string, surname: string): string {
  const normalize = (s: string) =>
    s.toLowerCase().replace(/[æ]/g, 'ae').replace(/[ø]/g, 'o').replace(/[å]/g, 'a')
  return `${normalize(forename)}.${normalize(surname)}@example.no`
}
